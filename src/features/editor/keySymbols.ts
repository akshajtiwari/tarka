const byExtension: Record<string, string> = {
  js: 'js',
  jsx: 'js',
  mjs: 'js',
  cjs: 'js',
  ts: 'js',
  tsx: 'js',
  py: 'py',
  html: 'html',
  htm: 'html',
  xml: 'html',
  css: 'css',
  json: 'json',
  md: 'md',
};

export function symbolsFor(path: string): string[] {
  const ext = path.split('.').pop()?.toLowerCase() ?? '';
  return sets[byExtension[ext] ?? 'js'];
}
